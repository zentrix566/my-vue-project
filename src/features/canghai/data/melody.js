// 将分段展开为带绝对起始拍的音符序列
export function buildNoteList() {
  const notes = []
  let beat = 0
  let id = 0
  for (const phrase of PHRASES) {
    for (const [pitch, dur] of phrase.notes) {
      notes.push({
        id: id++,
        pitch,
        lane: LANE_OF[pitch],
        startBeat: beat,
        beats: dur
      })
      beat += dur
    }
    beat += 0 // 段落间无缝衔接（每段恰好填满 4 拍）
  }
  return notes
}

export const TOTAL_BEATS = PHRASES.reduce(
  (sum, p) => sum + p.notes.reduce((s, n) => s + n[1], 0),
  0
)
